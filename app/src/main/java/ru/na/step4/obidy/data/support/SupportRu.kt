object SupportScreens {
    fun title(route: String?): String {
        val r = route.orEmpty()
        return when {
            r.isBlank() || r == "home" -> "Главный экран"
            r == "profile" -> "Анкета"
            r == "psych" -> "Электронный психолог"
            r.startsWith("analysis") -> "Самоанализ"
            r.startsWith("journal/ai") -> "ИИ дневника"
            r.startsWith("journal/settings") -> "Настройки"
            r.startsWith("journal/words") -> "Подбор слов"
            r.startsWith("journal/entry") -> "Запись дневника"
            r.startsWith("journal/entries") -> "Мои записи"
            r.startsWith("journal/pick") -> "Выбор места"
            r.startsWith("journal/personality") -> "Моя личность"
            r.startsWith("journal") -> "Дневник 12 шагов"
            r.startsWith("life/goal") -> "Цели"
            r.startsWith("life/idea") -> "Идеи"
            r.startsWith("life/event") || r.startsWith("life/calendar") -> "Календарь"
            r.startsWith("life/note") -> "Заметки"
            r.startsWith("life") -> "Цели и заметки"
            r.startsWith("messenger") -> "Мессенджер"
            r.startsWith("edit") -> "Обида"
            r.startsWith("situation") -> "Ситуация обиды"
            r.startsWith("assistant") -> "Голосовой консультант"
            r == "list" -> "Список обид"
            r == "guide" -> "Памятка"
            r == "categories" -> "Категории"
            r == "step4" -> "4 шаг · Обиды"
            r.startsWith("step") -> "Шаг программы"
            r.startsWith("soon") -> "Скоро"
            r == "support/report" || r == "support" -> SupportRu.report
            r == "support/idea" -> SupportRu.ideaTitle
            r == "cover" || r == "lock" -> SupportRu.belongingCover
            r == "general" -> SupportRu.belongingGeneral
            r.startsWith("activity") -> "Моя статистика"
            r.startsWith("family:") -> familyTitle(r.removePrefix("family:")) + " (все экраны)"
            else -> "Экран приложения"
        }
    }

    fun familyKey(route: String?): String {
        val r = route.orEmpty()
        return when {
            r.isBlank() || r == "home" -> "home"
            r == "cover" || r == "lock" || r.startsWith("lock") -> "cover"
            r == "profile" || r.startsWith("profile") -> "profile"
            r.startsWith("support") -> "support"
            r.startsWith("psych") -> "psych"
            r.startsWith("analysis") -> "analysis"
            r.startsWith("journal") -> "journal"
            r.startsWith("life") -> "life"
            r.startsWith("activity") -> "activity"
            r.startsWith("messenger") -> "messenger"
            r.startsWith("edit") ||
                r.startsWith("situation") ||
                r.startsWith("assistant") ||
                r == "list" ||
                r == "guide" ||
                r == "categories" ||
                r == "step4" ||
                r.startsWith("step") ||
                r.startsWith("soon") -> "resentments"
            else -> "home"
        }
    }

    fun familyTitle(key: String): String = when (key) {
        "profile" -> "Анкета"
        "psych" -> "Электронный психолог"
        "analysis" -> "Самоанализ"
        "journal" -> "Дневник 12 шагов"
        "life" -> "Цели и заметки"
        "activity" -> "Моя статистика"
        "messenger" -> "Мессенджер"
        "resentments" -> "Обиды / 4 шаг"
        "admin" -> "Админка"
        "support" -> SupportRu.reports
        "cover" -> SupportRu.belongingCover
        else -> "Главный экран"
    }
}
