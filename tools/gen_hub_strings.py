# -*- coding: utf-8 -*-
def esc(s: str) -> str:
    out = []
    for c in s:
        if ord(c) < 128 and c not in '"\\':
            out.append(c)
        else:
            out.append(f"\\u{ord(c):04x}")
    return "".join(out)


